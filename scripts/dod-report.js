#!/usr/bin/env node
/**
 * What: Runs the Definition of Done ([CAP-S09]) for every stage, sample and the final app - tests,
 *     cds lint, server start, README template, CHANGELOG-STAGE, .gitignore coverage, secret scan,
 *     mermaid diagrams, UI screenshots - and writes a pass/fail table to docs/dod-report.md.
 * Why: [CAP-S15] step 6 requires a pass/fail table across all folders; checking by script makes
 *     the table reproducible instead of hand-written.
 * If missing or unlinked: The DoD is checked by hand (or not at all) and docs/dod-report.md goes
 *     stale.
 *
 * Usage: npm run dod [-- --skip-tests] [-- --only <folder>]
 */
import { spawn } from 'node:child_process';
import { readdir, readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const args = process.argv.slice(2);
const skipTests = args.includes('--skip-tests');
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : undefined;

/** README headings required by the template in [CAP-S08]. */
const README_SECTIONS = [
  'Purpose', 'Module reference', 'Prerequisites', 'Folder structure', 'How to run', 'How to test',
  'Key concepts', 'When to use / When not to use', 'Impact & trade-offs', 'Visuals',
  'Deviations from guide', 'Troubleshooting', 'References',
];
const GITIGNORE = ['node_modules', 'gen', 'default-env.json', '*.mtar', '.env'];
/** Folders with a Fiori UI must have screenshots in docs/images/<folder>-*.png. */
const UI_FOLDERS = /^(stage-0[5-9]|stage-10|final-app|samples\/(draft-workflow|custom-fiori-section))/;
const SECRET_PATTERNS = [
  /-----BEGIN (RSA |EC |OPENSSH )?PRIVATE KEY-----/,
  /\bAKIA[0-9A-Z]{16}\b/,
  /"(clientsecret|client_secret)"\s*:\s*"[^"$<{][^"]{5,}"/i,
];
const SKIP_DIRS = new Set(['node_modules', 'gen', 'mta_archives', '.git', 'resources', 'coverage']);

const folders = await workspaceFolders();
const rows = [];
for (const folder of folders) {
  if (only && folder !== only) continue;
  console.log(`Checking ${folder} ...`);
  rows.push({ folder, ...(await check(folder)) });
}

const columns = ['tests', 'lint', 'starts', 'readme', 'changelog', 'gitignore', 'secrets', 'mermaid', 'screenshots'];
const mark = (/** @type {string} */ v) => ({ pass: '✅', fail: '❌', skip: '–', 'n/a': 'n/a' })[v] ?? v;
const table = [
  `| Folder | ${columns.join(' | ')} |`,
  `|---|${columns.map(() => '---').join('|')}|`,
  ...rows.map((r) => `| ${r.folder} | ${columns.map((c) => mark(r[c])).join(' | ')} |`),
];
const failures = rows.flatMap((r) => r.notes.map((n) => `- **${r.folder}**: ${n}`));
const report = `<!--
What: Generated Definition-of-Done report ([CAP-S09]) for every stage, sample and the final app.
Why: [CAP-S15] step 6 - one pass/fail table across all folders, produced by scripts/dod-report.js.
If missing or unlinked: The completion state of the guide must be checked by hand.
-->

# Definition of Done report

Generated by \`npm run dod\`${skipTests ? ' (tests skipped)' : ''} on ${new Date().toISOString().slice(0, 10)} with Node ${process.version}.

${table.join('\n')}

Legend: ✅ pass, ❌ fail, – skipped, n/a not applicable. *starts* = \`cds serve\` reaches
"server listening"; *readme* = all ${README_SECTIONS.length} template sections of [CAP-S08] present.

## Findings

${failures.length ? failures.join('\n') : 'None - every check passed.'}
`;
if (!only) await writeFile(path.join(root, 'docs', 'dod-report.md'), report);
console.log(`\n${table.join('\n')}\n\n${failures.join('\n')}`);
process.exitCode = rows.some((r) => columns.some((c) => r[c] === 'fail')) ? 1 : 0;

/** @param {string} folder */
async function check(folder) {
  const dir = path.join(root, folder);
  /** @type {string[]} */
  const notes = [];
  /** @type {Record<string, string>} */
  const r = {};

  if (skipTests) r.tests = 'skip';
  else {
    const t = await run('npm', ['test'], dir, 600_000);
    r.tests = t.code === 0 ? 'pass' : 'fail';
    if (t.code !== 0) notes.push(`npm test failed: ${tail(t.output)}`);
  }

  const lint = await run('npx', ['cds', 'lint', '.'], dir, 300_000);
  r.lint = lint.code === 0 ? 'pass' : 'fail';
  if (lint.code !== 0) notes.push(`cds lint: ${tail(lint.output)}`);

  const starts = await serverStarts(dir);
  r.starts = starts.ok ? 'pass' : 'fail';
  if (!starts.ok) notes.push(`cds serve did not start: ${tail(starts.output)}`);

  const readme = await text(path.join(dir, 'README.md'));
  const missing = README_SECTIONS.filter((s) => !new RegExp(`^## ${escape(s)}\\s*$`, 'm').test(readme ?? ''));
  r.readme = readme && !missing.length ? 'pass' : 'fail';
  if (missing.length) notes.push(`README sections missing: ${missing.join(', ')}`);

  if (folder.startsWith('stage-')) {
    r.changelog = (await text(path.join(dir, 'CHANGELOG-STAGE.md'))) ? 'pass' : 'fail';
    if (r.changelog === 'fail') notes.push('CHANGELOG-STAGE.md missing');
  } else r.changelog = 'n/a';

  const ignore = (await text(path.join(dir, '.gitignore'))) ?? '';
  const uncovered = GITIGNORE.filter((g) => !ignore.split('\n').some((l) => l.trim().replace(/\/$/, '') === g));
  r.gitignore = uncovered.length ? 'fail' : 'pass';
  if (uncovered.length) notes.push(`.gitignore lacks ${uncovered.join(', ')}`);

  const leaks = [];
  for (const file of await files(dir)) {
    const content = await text(path.join(dir, file));
    if (content && SECRET_PATTERNS.some((p) => p.test(content))) leaks.push(file);
  }
  r.secrets = leaks.length ? 'fail' : 'pass';
  if (leaks.length) notes.push(`possible secrets in ${leaks.join(', ')}`);

  r.mermaid = /```mermaid/.test(readme ?? '') ? 'pass' : 'fail';
  if (r.mermaid === 'fail') notes.push('README has no mermaid diagram');

  if (UI_FOLDERS.test(folder)) {
    const prefix = folder.replace('/', '-');
    const images = (await readdir(path.join(root, 'docs', 'images')).catch(() => [])).filter((f) => f.startsWith(`${prefix}-`) && f.endsWith('.png'));
    r.screenshots = images.length ? 'pass' : 'fail';
    if (!images.length) notes.push(`no screenshots docs/images/${prefix}-*.png`);
  } else r.screenshots = 'n/a';

  return { ...r, notes };
}

/** Starts `cds serve` on a free port and waits for "server listening". */
function serverStarts(/** @type {string} */ dir) {
  return new Promise((resolve) => {
    const child = spawn('npx', ['cds', 'serve', 'all', '--with-mocks', '--in-memory?', '--port', '0'], { cwd: dir, env: { ...process.env, NODE_ENV: '' }, detached: true });
    let output = '';
    const done = (/** @type {boolean} */ ok) => {
      clearTimeout(timer);
      try {
        process.kill(-child.pid, 'SIGTERM');
      } catch {
        // already exited
      }
      resolve({ ok, output });
    };
    const timer = setTimeout(() => done(false), 60_000);
    const onData = (/** @type {Buffer} */ d) => {
      output += d;
      if (/server listening on/.test(output)) done(true);
    };
    child.stdout.on('data', onData);
    child.stderr.on('data', onData);
    child.on('exit', () => done(/server listening on/.test(output)));
  });
}

/**
 * @param {string} cmd
 * @param {string[]} argv
 * @param {string} cwd
 * @param {number} timeout
 * @returns {Promise<{ code: number | null, output: string }>}
 */
function run(cmd, argv, cwd, timeout) {
  return new Promise((resolve) => {
    const child = spawn(cmd, argv, { cwd, timeout, env: { ...process.env, NODE_TEST_CONTEXT: undefined } });
    let output = '';
    child.stdout.on('data', (d) => (output += d));
    child.stderr.on('data', (d) => (output += d));
    child.on('close', (code) => resolve({ code, output }));
  });
}

async function workspaceFolders() {
  const out = [];
  for (const e of (await readdir(root, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    if (e.isDirectory() && e.name.startsWith('stage-')) out.push(e.name);
  }
  const samples = await readdir(path.join(root, 'samples'), { withFileTypes: true }).catch(() => []);
  for (const e of samples.filter((s) => s.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) out.push(`samples/${e.name}`);
  if (await exists(path.join(root, 'final-app'))) out.push('final-app');
  return out;
}

/** @param {string} dir @param {string} [rel] @returns {Promise<string[]>} */
async function files(dir, rel = '') {
  const out = [];
  for (const e of await readdir(path.join(dir, rel), { withFileTypes: true })) {
    if (SKIP_DIRS.has(e.name)) continue;
    const p = path.join(rel, e.name);
    if (e.isDirectory()) out.push(...(await files(dir, p)));
    else if (!/\.(png|jpe?g|mtar|zip|sqlite|db)$/i.test(e.name)) out.push(p);
  }
  return out;
}

/** @param {string} file */
async function text(file) {
  try {
    return await readFile(file, 'utf8');
  } catch {
    return undefined;
  }
}

/** @param {string} file */
async function exists(file) {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

/** @param {string} s */
function escape(s) {
  return s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
}

/** @param {string} s */
function tail(s) {
  return s.trim().split('\n').slice(-3).join(' / ').slice(0, 300);
}
