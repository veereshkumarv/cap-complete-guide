#!/usr/bin/env node
/**
 * What: Creates a stand-alone client project from the final reference app (or another stage):
 *     copies the folder outside this repository without dependencies, build output, local
 *     databases or credentials, and renames the project-level identifiers (npm package, MTA ID and
 *     module names, XSUAA app name, Event Mesh client, pipeline app name, extension target).
 * Why: docs/client-adoption-guide.md - developers start every new CAP project from the reviewed,
 *     tested template in one command instead of copying and renaming by hand (where a forgotten
 *     "acme-procurement" in mta.yaml or xs-security.json breaks the deployment).
 * If missing or unlinked: New projects are copied by hand; stale names, copied credentials or
 *     node_modules end up in client repositories.
 *
 * Usage: npm run new-project -- <target-folder> <project-name> [--from <folder>]
 *        e.g. npm run new-project -- ../contoso-purchasing contoso-purchasing
 */
import { cp, readFile, writeFile, access, readdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const args = process.argv.slice(2);
const fromIndex = args.indexOf('--from');
const from = fromIndex >= 0 ? args.splice(fromIndex, 2)[1] : 'final-app';
const [target, name] = args;

if (!target || !name || !/^[a-z][a-z0-9-]{2,40}$/.test(name)) {
  console.error('Usage: npm run new-project -- <target-folder> <project-name> [--from <folder>]');
  console.error('       <project-name>: lower case letters, digits and dashes, e.g. contoso-purchasing');
  process.exit(2);
}
const src = path.join(root, from);
const dest = path.resolve(process.cwd(), target);
if (dest === root || dest.startsWith(root + path.sep)) {
  console.error('The target must be outside this repository (it becomes its own project / git repository).');
  process.exit(2);
}
try {
  await access(dest);
  console.error(`${dest} already exists - refusing to overwrite.`);
  process.exit(2);
} catch {
  // expected
}
try {
  await access(path.join(src, 'package.json'));
} catch {
  console.error(`${from} is not a project folder of this repository.`);
  process.exit(2);
}

const SKIP = new Set(['node_modules', 'gen', 'mta_archives', 'dist', 'coverage', 'resources', 'default-env.json', '.cdsrc-private.json', '.env', '.base']);
const SKIP_PATTERN = /\.(mtar|sqlite|sqlite-\w+|db|log)$|^\.env\./;
await cp(src, dest, { recursive: true, filter: (f) => !SKIP.has(path.basename(f)) && !SKIP_PATTERN.test(path.basename(f)) });

// project-level identifiers of the template -> new name (the domain model stays - replace it next)
const oldPkg = JSON.parse(await readFile(path.join(src, 'package.json'), 'utf8')).name; // e.g. procurement-final-app
const oldApp = from === 'final-app' ? 'acme-procurement' : oldPkg; // MTA ID / module prefix
const compact = (s) => s.replace(/-/g, '');
const replacements = [
  [`${compact(oldApp)}procurement`, `${compact(name)}procurement`], // html5 module name
  [oldApp, name],
  [oldPkg, name],
];
const TEXT = /\.(js|mjs|cjs|json|ya?ml|cds|md|http|properties|sh|html|xml)$/;
let changed = 0;
for (const file of await walk(dest)) {
  if (!TEXT.test(file) || file.endsWith('package-lock.json')) continue;
  const before = await readFile(file, 'utf8');
  let after = before;
  for (const [a, b] of replacements) after = after.split(a).join(b);
  if (after !== before) {
    await writeFile(file, after);
    changed++;
  }
}
const pkgFile = path.join(dest, 'package.json');
const pkg = JSON.parse(await readFile(pkgFile, 'utf8'));
pkg.name = name;
pkg.description = `${name} - created from the CAP complete guide (${from})`;
delete pkg['//'];
await writeFile(pkgFile, `${JSON.stringify({ '//': [
  `What: npm manifest of ${name}, created from the CAP complete guide (${from}).`,
  'Why: CAP runtime, plugins, scripts and the cds configuration per profile - see the guide stage READMEs for every setting.',
  'If missing or unlinked: The folder is no longer a runnable CAP project.',
], ...pkg }, null, 2)}\n`);
// lock files of the sub-projects still carry the old names; they are regenerated by npm install
console.log(`Created ${dest} from ${from} (${changed} files renamed to "${name}").
Next:
  cd ${path.relative(process.cwd(), dest) || '.'}
  git init && npm install && npm test
  # then replace the ACME domain (db/, srv/, app/) - see docs/client-adoption-guide.md`);

/** @param {string} dir @returns {Promise<string[]>} */
async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir)) {
    const p = path.join(dir, e);
    if ((await stat(p)).isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}
